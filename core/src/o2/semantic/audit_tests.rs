#[test]
fn benchmark_quality_matches_the_runtime_result_window() {
    for limit in [1, 2] {
        let (t, records) = root();
        let r = t.path();
        let view = policy::inspect(r).unwrap();
        let mut p = view.policy;
        p.memory.search_limit = limit;
        policy::update(r, &view.revision, Some(p)).unwrap();
        let cases = suite(&records);
        let baseline = cases
            .cases
            .iter()
            .map(|c| {
                memory::search(r, &request(&c.query))
                    .unwrap()
                    .into_iter()
                    .map(|h| h.memory.id)
                    .collect::<Vec<_>>()
            })
            .collect::<Vec<_>>();
        let result = benchmark(r, cases.clone()).unwrap();
        let report: Report = serde_json::from_value(result["report"].clone()).unwrap();
        for (case, runtime) in report.results.iter().zip(baseline) {
            assert_eq!(case.fts_ids, runtime);
            assert!(case.hybrid_ids.len() <= limit as usize);
            assert!(case.hybrid_recall <= limit as f64 / 3. + 1e-9);
        }
        assert_eq!(report.passed, limit > 1);
        let enabled = apply_gate(
            r,
            &report.id,
            result["checksum"].as_str().unwrap(),
            true,
            true,
        );
        if limit == 1 {
            assert!(
                enabled.is_err(),
                "an unobservable gain must not authorize retrieval"
            );
            assert_eq!(report.hybrid_recall, report.fts_recall);
        } else {
            enabled.unwrap();
            for case in report.results {
                let runtime = memory::search(r, &request(&case.query)).unwrap();
                assert_eq!(
                    case.hybrid_ids,
                    runtime.into_iter().map(|h| h.memory.id).collect::<Vec<_>>()
                );
            }
        }
    }
}

#[test]
fn legacy_benchmarks_and_approvals_are_inspectable_but_cannot_enable_retrieval() {
    // Captured from the actual pre-fix binary, not generated by the current DTO.
    let frozen: serde_json::Value = serde_json::from_str(include_str!(
        "../../../tests/fixtures/o2-semantic/legacy-report.json"
    ))
    .unwrap();
    let old: Report = serde_json::from_value(frozen["report"].clone()).unwrap();
    assert_eq!(
        benchmark::checksum(&old).unwrap(),
        frozen["checksum"].as_str().unwrap()
    );
    let (t, records) = root();
    let r = t.path();
    let result = benchmark(r, suite(&records)).unwrap();
    let mut legacy = result["report"].clone();
    legacy.as_object_mut().unwrap().remove("benchmark_recipe");
    legacy["id"] = serde_json::json!(uuid::Uuid::new_v4().to_string());
    let mut old_policy = policy::load(r).unwrap().memory;
    old_policy.semantic_enabled = false;
    legacy["settings"] = serde_json::json!(digest(&serde_json::to_vec(&old_policy).unwrap()));
    let report: Report = serde_json::from_value(legacy.clone()).unwrap();
    // Use the typed legacy serialization order, as the original implementation did.
    let checksum = benchmark::checksum(&report).unwrap();
    let key = gate::key(
        &report.project,
        &report.corpus,
        &report.settings,
        &report.backend.recipe,
    );
    let (db, _) = database(r).unwrap();
    schema::audit(&db, "semantic_benchmark", &report.id, legacy).unwrap();
    schema::audit(&db, "semantic_gate", &key,
        serde_json::json!({"enabled":true,"report_id":report.id,"checksum":checksum,"project":report.project})).unwrap();
    drop(db);
    assert_eq!(memory::search(r, &request("password")).unwrap().len(), 1);
    let status = status(r, &Access::default()).unwrap();
    assert!(status["approved_event"].is_null());
    assert_eq!(status["reports"][0]["approvable"], false);
    assert_eq!(status["reports"][0]["checksum"], checksum);
    assert!(status["reports"][0]["report"]
        .get("benchmark_recipe")
        .is_none());
    assert!(apply_gate(r, &report.id, &checksum, true, true).is_err());
    apply_gate(r, &report.id, &checksum, false, true).unwrap();
    approve(r, &records);
    assert!(memory::search(r, &request("password")).unwrap().len() > 1);
}
