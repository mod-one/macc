use macc_core::{
    config::CanonicalConfig,
    plan::{Action, ActionPlan},
    resolve::{self, PlanningContext},
    ProjectPaths,
};
use std::{collections::BTreeMap, fs, path::Path};
fn setup(root: &Path, tools: &[&str]) -> (ProjectPaths, CanonicalConfig) {
    let paths = ProjectPaths::from_root(root);
    fs::create_dir_all(&paths.macc_dir).unwrap();
    let mut config = CanonicalConfig::default();
    config.tools.enabled = tools.iter().map(|s| s.to_string()).collect();
    config.tools.config.insert(
        "codex".into(),
        serde_json::json!({"rules_enabled":true,"context":{"protect":true}}),
    );
    config.context_engine = Some(macc_core::o2::policy::ContextPolicy {
        enabled: false,
        ..Default::default()
    });
    config.code_intelligence = Some(macc_core::o2::policy::CodePolicy {
        enabled: false,
        ..Default::default()
    });
    fs::write(&paths.config_path, config.to_yaml().unwrap()).unwrap();
    (paths, config)
}
fn plan(paths: &ProjectPaths, config: &CanonicalConfig) -> ActionPlan {
    let resolved = resolve::resolve(config, &Default::default());
    let context = PlanningContext {
        paths,
        resolved: &resolved,
        materialized_units: &[],
    };
    macc_core::project_context::plan_tools(&context, &macc_registry::default_registry()).unwrap()
}
fn body(plan: &ActionPlan, path: &str) -> Option<String> {
    plan.actions.iter().find_map(|a| match a {
        Action::WriteFile {
            path: p, content, ..
        } if p == path => Some(String::from_utf8(content.clone()).unwrap()),
        _ => None,
    })
}
fn apply(paths: &ProjectPaths, plan: &ActionPlan) {
    macc_core::apply_operations(
        paths,
        &macc_core::plan::collect_plan_operations(paths, plan),
        false,
        |_, _, _| {},
    )
    .unwrap();
}
#[test]
fn every_native_context_is_deterministic_and_has_no_phantom_workflows() {
    let temp = std::env::temp_dir().join(format!("macc-context-native-{}", std::process::id()));
    fs::create_dir_all(&temp).unwrap();
    let (paths, mut cfg) = setup(&temp, &["codex", "vibe", "claude", "gemini", "agy"]);
    cfg.standards.inline = BTreeMap::from([("language".into(), "French".into())]);
    let p = plan(&paths, &cfg);
    assert_eq!(p, plan(&paths, &cfg));
    for path in ["AGENTS.md", "CLAUDE.md", "GEMINI.md"] {
        let text = body(&p, path).unwrap();
        for forbidden in [
            "`validate`",
            "`implement`",
            "/validate",
            "/implement",
            "pnpm ",
            "`explore`",
            "BMAD",
            "Use English",
        ] {
            assert!(!text.contains(forbidden), "{path}: {forbidden}");
        }
        assert!(text.contains("language: French"));
        assert_eq!(
            p.actions
                .iter()
                .filter(|a| matches!(a,Action::WriteFile{path:p,..} if p==path))
                .count(),
            1
        );
    }
    fs::remove_dir_all(temp).unwrap();
}
#[test]
fn shared_gemini_and_custom_targets_reference_only_planned_assets() {
    let root = std::env::temp_dir().join(format!("macc-context-shared-{}", std::process::id()));
    fs::create_dir_all(&root).unwrap();
    let (paths, mut cfg) = setup(&root, &["gemini", "agy"]);
    let shared = plan(&paths, &cfg);
    assert_eq!(
        shared
            .actions
            .iter()
            .filter(|a| matches!(a,Action::WriteFile{path,..} if path=="GEMINI.md"))
            .count(),
        1
    );
    let text = body(&shared, "GEMINI.md").unwrap();
    assert!(text.contains("Context consumers: agy, gemini"));
    assert!(text.contains(".gemini/styleguide.md"));
    cfg.tools.enabled = vec!["agy".into()];
    let agy = plan(&paths, &cfg);
    assert!(!body(&agy, "GEMINI.md")
        .unwrap()
        .contains(".gemini/styleguide.md"));
    cfg.tools.enabled = vec!["gemini".into()];
    cfg.tools.config.insert(
        "gemini".into(),
        serde_json::json!({"context":{"fileName":["PROJECT.md"]}}),
    );
    let custom = plan(&paths, &cfg);
    assert!(body(&custom, "PROJECT.md").is_some());
    assert!(body(&custom, "GEMINI.md").is_none());
    fs::remove_dir_all(root).unwrap();
}
#[test]
fn owned_context_migrates_with_backup_but_user_edits_remain_protected() {
    let root = std::env::temp_dir().join(format!("macc-context-owned-{}", std::process::id()));
    fs::create_dir_all(&root).unwrap();
    let (paths, mut cfg) = setup(&root, &["codex"]);
    // Simulate an unchanged context generated by the old renderer (no v2 marker).
    let legacy = b"# Generated instructions\nUse `validate` and `implement`.\n";
    let mut initial = ActionPlan::new();
    initial.actions.push(Action::WriteFile {
        path: "AGENTS.md".into(),
        content: legacy.to_vec(),
        scope: macc_core::plan::Scope::Project,
    });
    apply(&paths, &initial);
    cfg.standards
        .inline
        .insert("language".into(), "French".into());
    let next = plan(&paths, &cfg);
    assert!(body(&next, "AGENTS.md").is_some());
    apply(&paths, &next);
    assert!(fs::read_to_string(root.join("AGENTS.md"))
        .unwrap()
        .contains("French"));
    assert!(
        fs::read_dir(&paths.backups_dir).unwrap().any(|entry| {
            fs::read(entry.unwrap().path().join("AGENTS.md")).is_ok_and(|bytes| bytes == legacy)
        }),
        "the previous generated context must be recoverable"
    );
    fs::write(root.join("AGENTS.md"), "operator custom instructions").unwrap();
    let preserved = plan(&paths, &cfg);
    assert!(body(&preserved, "AGENTS.md").is_none());
    assert!(preserved
        .warnings
        .iter()
        .any(|w| w.contains("customized context")));
    apply(&paths, &preserved);
    assert_eq!(
        fs::read_to_string(root.join("AGENTS.md")).unwrap(),
        "operator custom instructions"
    );
    let worker = root.join("worker");
    fs::create_dir_all(&worker).unwrap();
    fs::write(worker.join("AGENTS.md"), "worker custom instructions").unwrap();
    macc_core::sync_context_files_from_root(&root, &worker, &cfg).unwrap();
    assert_eq!(
        fs::read_to_string(worker.join("AGENTS.md")).unwrap(),
        "worker custom instructions"
    );
    fs::remove_dir_all(root).unwrap();
}
