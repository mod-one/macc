#[test]
fn conflicting_writes_are_refused_before_apply_mutates_any_file() {
    let root = std::env::temp_dir().join(format!("macc-context-conflict-{}", std::process::id()));
    fs::create_dir_all(&root).unwrap();
    let (paths, _) = setup(&root, &["gemini", "agy"]);
    let mut p = ActionPlan::new();
    for value in ["one", "two"] {
        p.actions.push(Action::WriteFile {
            path: "GEMINI.md".into(),
            content: value.as_bytes().to_vec(),
            scope: macc_core::plan::Scope::Project,
        });
    }
    let conflict_ops = macc_core::plan::collect_plan_operations(&paths, &p);
    assert!(conflict_ops[0].metadata.generation_conflict.is_some());
    assert!(macc_core::apply_operations(&paths, &conflict_ops, false, |_, _, _| {}).is_err());
    assert!(macc_core::apply_plan(&paths, &mut p, false)
        .unwrap_err()
        .to_string()
        .contains("Conflicting generated writes"));
    assert!(!root.join("GEMINI.md").exists());
    fs::remove_dir_all(root).unwrap();
}

#[test]
fn installed_skills_and_language_overrides_are_resolved_per_consumer() {
    let root = std::env::temp_dir().join(format!("macc-context-consumers-{}", std::process::id()));
    fs::create_dir_all(&root).unwrap();
    let (paths, mut cfg) = setup(&root, &["gemini", "agy"]);
    cfg.standards
        .inline
        .insert("language".into(), "French".into());
    cfg.tools
        .config
        .insert("gemini".into(), serde_json::json!({"language":"Spanish"}));
    let resolved = resolve::resolve(&cfg, &Default::default());
    let ctx = PlanningContext {
        paths: &paths,
        resolved: &resolved,
        materialized_units: &[],
    };
    assert!(
        macc_core::project_context::plan_tools(&ctx, &macc_registry::default_registry())
            .unwrap_err()
            .to_string()
            .contains("incompatible tool language")
    );
    cfg.tools
        .config
        .insert("agy".into(), serde_json::json!({"language":"Spanish"}));
    cfg.selections = Some(macc_core::config::SelectionsConfig {
        skills: vec!["real-check".into()],
        ..Default::default()
    });
    fs::create_dir_all(root.join(".agents/skills/real-check")).unwrap();
    fs::write(
        root.join(".agents/skills/real-check/SKILL.md"),
        "# Real check",
    )
    .unwrap();
    let p = plan(&paths, &cfg);
    let content = body(&p, "GEMINI.md").unwrap();
    assert!(content.contains("language: Spanish"));
    assert!(content.contains(".agents/skills/real-check/SKILL.md"));
    assert!(!content.contains(".gemini/skills/real-check/SKILL.md"));
    assert!(p
        .warnings
        .iter()
        .any(|w| w.contains("gemini") && w.contains("real-check")));
    fs::remove_dir_all(root).unwrap();
}

